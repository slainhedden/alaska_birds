for (const bird of birds) {
  if (ids.has(bird.id)) {
    throw new Error(`Duplicate bird id: ${bird.id}`);
  }

  ids.add(bird.id);

  if (
    !bird.commonName ||
    !bird.scientificName ||
    !bird.habitat ||
    bird.fieldMarks.length === 0 ||
    bird.learningTags.length === 0 ||
    !bird.image.sourceUrl ||
    !bird.sound.source.sourceUrl
  ) {
    throw new Error(`Incomplete bird record: ${bird.commonName}`);
  }
}

