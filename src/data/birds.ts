interface BirdSeed {
  commonName: string;
  scientificName: string;
  likelihood: Likelihood;
  priority: number;
  appearance: string;
  habitat: string;
  habitats: HabitatTag[];
  fieldMarks: string[];
  quickHint: string;
  confusion: string;
  memoryHook: string;
  soundDescription: string;
  soundMnemonic: string;
  listenFor: string;
  learningTags: LearningTag[];
  sourceNotes: string;
  audio: MediaSource | null;
  audioUrl: string | null;
}

function slugId(name: string) {
  return name
    .toLowerCase()
    .replace(/'/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

function guideSlug(name: string) {
  return name.replace(/'/g, "").replace(/ /g, "_");
}

function allAboutBirds(name: string) {
  return `https://www.allaboutbirds.org/guide/${guideSlug(name)}`;
}

function xenoCantoSearch(name: string) {
  return `https://xeno-canto.org/explore?query=${encodeURIComponent(name)}`;
}

function wikimediaImageSearch(name: string) {
  return `https://commons.wikimedia.org/wiki/Special:MediaSearch?type=image&search=${encodeURIComponent(
    name,
  )}`;
}

function placeholderImage(name: string): MediaSource {
  return {
    kind: "placeholder",
    sourceName: "Wikimedia Commons image search",
    sourceUrl: wikimediaImageSearch(name),
    license: "Varies by file; not embedded until a reusable file is selected.",
    credit: "No local image embedded.",
    notes: "The app uses a field-guide placeholder and links to licensed image candidates.",
  };
}

function externalSound(name: string): MediaSource {
  return {
    kind: "external",
    sourceName: "Xeno-canto recording search",
    sourceUrl: xenoCantoSearch(name),
    license: "Varies by recording; verify Creative Commons terms before embedding.",
    credit: "No local audio embedded.",
    notes: "Used as a source link for practice and attribution review.",
  };
}

