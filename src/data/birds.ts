function createBird(seed: BirdSeed): Bird {
  const soundSource = seed.audio ?? externalSound(seed.commonName);

  return {
    id: slugId(seed.commonName),
    commonName: seed.commonName,
    scientificName: seed.scientificName,
    likelihood: seed.likelihood,
    priority: seed.priority,
    appearance: seed.appearance,
    habitat: seed.habitat,
    habitats: seed.habitats,
    fieldMarks: seed.fieldMarks,
    quickHint: seed.quickHint,
    confusion: seed.confusion,
    memoryHook: seed.memoryHook,
    sound: {
      description: seed.soundDescription,
      mnemonic: seed.soundMnemonic,
      listenFor: seed.listenFor,
      source: soundSource,
      ...(seed.audioUrl ? { audioUrl: seed.audioUrl } : {}),
    },
    image: placeholderImage(seed.commonName),
    learningTags: seed.learningTags,
    sourceNotes: seed.sourceNotes,
    researchSources: [
      ...sourceCore,
      EBIRD_FINDING_BIRDS,
      allAboutBirds(seed.commonName),
      soundSource.sourceUrl,
      wikimediaImageSearch(seed.commonName),
    ],
  };
}

